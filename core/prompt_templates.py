def build_chapter_writing_prompt(
    doc_title: str,
    genre: str,
    chapter_index: int,
    total_chapters: int,
    chapter_title: str,
    chapter_outline: str,
    prev_chapter_summary: str,
    next_chapter_title: str = "",
    target_words: int = 900
) -> str:
    """
    【核心优化】携带前后长程记忆、细纲任务卡、爽点与章末钩子的增强型章节扩写提示词
    """
    is_novel = "小说" in genre or "文学" in genre

    novel_guide = ""
    if is_novel:
        novel_guide = f"""
{ANTI_AI_WRITING_RULES}

【网文专属写作细则】：
- 聚焦本章核心矛盾，迅速展开场景，避免冗长无趣的背景说教；
- 运用丰富的感官细节（视觉、听觉、触觉）强化代入感；
- 结尾必须严格落地大纲中规定的【章末钩子】，留下强烈的悬念断点！
"""

    return f"""你正在撰写长篇作品《{doc_title}》（文体：{genre}）。
现在需要撰写第 {chapter_index}/{total_chapters} 章节的详实正文。

【前序上下文与过渡要求】
{f"- 上一章节核心摘要：{prev_chapter_summary}" if prev_chapter_summary else "- 本章节为开篇首章：务必先声夺人，在前300字内抓住读者眼球，迅速切入核心情境！"}
{f"- 后续章节预告：下一章将展开《{next_chapter_title}》，本章结尾必须自然铺垫、设下悬念过渡。" if next_chapter_title else "- 本章节为收束终章：需将前文矛盾推向顶峰并圆满闭环，给出有力的收尾。"}

【当前章节蓝图与任务规划】
- 章节标题：{chapter_title}
- 本章大纲与任务要点：
{chapter_outline}
- 建议篇幅：约 {target_words} 字

{novel_guide}

【写作与排版格式规范】
1. 以二级标题 `## {chapter_title}` 开始，严禁出现多余的客套废话或AI开头语（如“好的”、“接下来我将…”）。
2. 全文充实生动，语言流畅，段落适中（避免大段不分段的死板文字）。
3. 严格使用标准 Markdown 语法排版。"""

def build_polish_prompt(raw_text: str, polish_mode: str, extra_instruction: str = "") -> str:
    """
    构建文本润色与精炼提示词（融合去AI味）
    """
    mode_desc = POLISH_MODES.get(polish_mode, "提升语言表达质感与逻辑连贯性")
    
    extra_rules = ""
    if "去AI味" in polish_mode or "网文" in polish_mode:
        extra_rules = ANTI_AI_WRITING_RULES

    return f"""你是一位资深文学总监与顶级文本精修专家。请对以下原始文本进行深度重构与润色。

【润色模式】：{polish_mode}
【核心目标】：{mode_desc}
{f"【特殊用户指令】：{extra_instruction}" if extra_instruction else ""}
{extra_rules}

【原始待改文本】
```
{raw_text}
```

【处理要求】
请严格按以下结构输出 Markdown：

### 🌟 润色后成果
（输出润色重构后的完整文本，保持排版工整优雅，彻底去除套话与语病）

### 📝 优化与修改要点解析
（分点陈述对原句的改动逻辑、修复的病句错词/套话，以及为何能带来表达质感的显著提升）"""
