def build_system_prompt(genre: str) -> str:
    """构建特定文体的系统级角色设定提示词"""
    role_info = GENRE_ROLES.get(genre, GENRE_ROLES["文学创作与网文小说"])
    return f"""你是一位享誉业界的【{role_info['title']}】。
【核心定位】：{role_info['description']}
【行文规范】：{role_info['style_guide']}

【输出原则】：
1. 始终使用标准 CommonMark 规范输出，结构层次分明。
2. 严禁无意义的口头寒暄（如“好的，这是为您生成的…”），直接输出高质量成果。
3. 重点突出，合理运用引用块、加粗、标准结构化列表。"""

